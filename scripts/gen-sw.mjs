// Post-build: writes out/sw.js with a precache list of every exported file so the whole
// game (all pages, JS, fonts) works offline after the first visit.
import { createHash } from "node:crypto";
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const OUT = "out";
const BASE = (process.env.NEXT_PUBLIC_BASE_PATH || "").replace(/\/$/, "");
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else files.push(p);
  }
})(OUT);

const urls = [];
let sig = createHash("sha1");
for (const f of files.sort()) {
  const rel = relative(OUT, f).split(sep).join("/");
  if (rel === "sw.js" || rel.endsWith(".map") || rel.startsWith("_next/static/chunks/") && rel.endsWith(".txt")) continue;
  sig.update(rel + ":" + statSync(f).size);
  if (rel === "index.html") urls.push(`${BASE}/`);
  else if (rel.endsWith("/index.html")) urls.push(`${BASE}/${rel.slice(0, -"index.html".length)}`);
  else urls.push(`${BASE}/${rel}`);
}
const version = sig.digest("hex").slice(0, 10);

const sw = `/* PROJECT 26 service worker — generated by scripts/gen-sw.mjs */
const CACHE = "p26-${version}";
const BASE = ${JSON.stringify(BASE)};
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener("install", (e) => {
  e.waitUntil(
    caches.open(CACHE).then(async (c) => {
      // best-effort: one bad file must not block the install
      await Promise.all(PRECACHE.map((u) => c.add(new Request(u, { cache: "reload" })).catch(() => {})));
    }).then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("p26-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  // Hashed build files (/_next/static/…) never change for a given URL → safe to serve from cache first.
  if (url.pathname.includes("/_next/static/")) {
    e.respondWith(
      caches.match(req).then((hit) => hit || fetch(req).then((res) => {
        if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
        return res;
      }))
    );
    return;
  }

  // Everything else (pages, page data, manifest, icons) is network-first so an update is never hidden behind
  // a stale copy; the cache is the offline fallback. A 4s timeout keeps a bad connection from hanging the app.
  const fresh = new Promise((resolve, reject) => {
    const t = setTimeout(() => reject(new Error("timeout")), 4000);
    fetch(req).then((res) => { clearTimeout(t); resolve(res); }, (err) => { clearTimeout(t); reject(err); });
  });
  e.respondWith(
    fresh.then((res) => { if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); } return res; })
      .catch(() => caches.match(req).then((r) => r || (req.mode === "navigate" ? caches.match(req, { ignoreSearch: true }).then((x) => x || caches.match(BASE + "/")) : undefined)))
  );
});
`;
writeFileSync(join(OUT, "sw.js"), sw);
console.log(`service worker written: ${urls.length} files precached (v${version})`);
